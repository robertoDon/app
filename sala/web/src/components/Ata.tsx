import { useEffect, useState } from "react";
import { sb, type Mensagem, type Tarefa } from "../supabase";
import { IconeFechar } from "./Icones";
import { gravado, idioma, locale, t } from "../i18n";

type Props = { salaId: string; salaNome: string; autor: (m: Mensagem) => string; nome: (uid: string | null) => string; fechar: () => void };

const dia = (iso: string) => new Date(iso).toLocaleDateString(locale(), { day: "numeric", month: "short", year: "numeric" }).replace(".", "");
const diaHora = (iso: string) => new Date(iso).toLocaleString(locale(), { day: "numeric", month: "short", hour: "2-digit", minute: "2-digit" }).replace(".", "");
const limpa = (tf: string) => tf.replace(/\s+/g, " ").trim();
const esc = (tf: string) => tf.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]!);

type Dados = { propostas: Mensagem[]; notas: Map<number, string>; tarefas: Tarefa[]; conversa: Mensagem[] | null; desde: string | null };

// Ata da sala: decisões e tarefas de um período (e a conversa, se quiser), em .md ou para imprimir/PDF.
export function Ata({ salaId, salaNome, autor, nome, fechar }: Props) {
  const [dias, setDias] = useState<7 | 30 | 0>(7);
  const [incluirConversa, setConversa] = useState(false);
  const [indo, setIndo] = useState(false);

  useEffect(() => {
    const esc = (e: KeyboardEvent) => e.key === "Escape" && fechar();
    window.addEventListener("keydown", esc);
    return () => window.removeEventListener("keydown", esc);
  }, [fechar]);

  const juntar = async (): Promise<Dados> => {
    const desde = dias ? new Date(Date.now() - dias * 864e5).toISOString() : null;
    // propostas: criadas ou decididas no período, e todas as que ainda esperam decisão
    let qp = sb.from("mensagens").select("*").eq("sala_id", salaId).eq("tipo", "proposta").eq("apagada", false).order("id");
    if (desde) qp = qp.or(`criada_em.gte.${desde},decidida_em.gte.${desde},estado.eq.pendente`);
    let qd = sb.from("mensagens").select("*").eq("sala_id", salaId).eq("tipo", "decisao").order("id");
    if (desde) qd = qd.gte("criada_em", desde);
    let qt = sb.from("tarefas").select("*").eq("sala_id", salaId).neq("estado", "cancelada").order("id");
    if (desde) qt = qt.or(`criada_em.gte.${desde},concluida_em.gte.${desde},estado.eq.aberta`);
    const [p, dec, tf] = await Promise.all([qp, qd, qt]);
    let conversa: Mensagem[] | null = null;
    if (incluirConversa) {
      conversa = [];
      for (let de = 0; de < 10000; de += 1000) { // o servidor entrega no máximo 1.000 por vez
        let q = sb.from("mensagens").select("*").eq("sala_id", salaId).eq("apagada", false).order("id").range(de, de + 999);
        if (desde) q = q.gte("criada_em", desde);
        const { data } = await q;
        conversa.push(...((data as Mensagem[]) ?? []));
        if (!data || data.length < 1000) break;
      }
    }
    const notas = new Map<number, string>();
    ((dec.data as Mensagem[]) ?? []).filter((m) => m.responde_a && m.texto !== "Aprovada." && m.texto !== "Recusada.").forEach((m) => notas.set(m.responde_a!, m.texto));
    return { propostas: (p.data as Mensagem[]) ?? [], notas, tarefas: (tf.data as Tarefa[]) ?? [], conversa, desde };
  };

  const agenteDe = (agente: string, uid: string | null) => t(`${agente} de ${nome(uid).split(" ")[0]}`, `${nome(uid).split(" ")[0]}'s ${agente}`);
  const quemFaz = (tf: Tarefa) => (tf.responsavel_agente ? agenteDe(tf.responsavel_agente, tf.responsavel) : tf.responsavel ? nome(tf.responsavel) : t("sem responsável", "unassigned"));
  const periodo = (d: Dados) => {
    const hoje = dia(new Date().toISOString());
    return d.desde ? t(`${dia(d.desde)} a ${hoje}`, `${dia(d.desde)} to ${hoje}`) : t(`todo o histórico, até ${hoje}`, `all history, through ${hoje}`);
  };

  const markdown = (d: Dados) => {
    const decididas = d.propostas.filter((p) => p.estado !== "pendente");
    const pendentes = d.propostas.filter((p) => p.estado === "pendente");
    const abertas = d.tarefas.filter((tf) => tf.estado === "aberta");
    const feitas = d.tarefas.filter((tf) => tf.estado === "feita");
    const agora = diaHora(new Date().toISOString());
    const l = [`# ${t("Ata", "Minutes")} · ${salaNome}`, "", t(`Período: ${periodo(d)}. Gerada pelo The Sala em ${agora}.`, `Period: ${periodo(d)}. Generated by The Sala on ${agora}.`), ""];
    l.push(`## ${t("Decisões", "Decisions")} (${decididas.length})`, "");
    if (!decididas.length) l.push(t("Nenhuma decisão no período.", "No decisions in this period."), "");
    decididas.forEach((p) => {
      const quem = nome(p.decidida_por), quando = dia(p.decidida_em!), de = autor(p), texto = limpa(p.texto);
      l.push(p.estado === "aprovada"
        ? t(`- **Aprovada** por ${quem} em ${quando}. Proposta de ${de}: ${texto}`, `- **Approved** by ${quem} on ${quando}. Proposed by ${de}: ${texto}`)
        : t(`- **Recusada** por ${quem} em ${quando}. Proposta de ${de}: ${texto}`, `- **Declined** by ${quem} on ${quando}. Proposed by ${de}: ${texto}`));
      if (d.notas.get(p.id)) l.push(`  - ${t("Comentário", "Comment")}: ${limpa(gravado(d.notas.get(p.id)!))}`);
    });
    if (pendentes.length) l.push("", `## ${t("Aguardando decisão", "Awaiting decision")} (${pendentes.length})`, "", ...pendentes.map((p) => `- ${t("Proposta de", "Proposed by")} ${autor(p)}: ${limpa(p.texto)}`));
    l.push("", `## ${t("Tarefas abertas", "Open tasks")} (${abertas.length})`, "");
    if (!abertas.length) l.push(t("Nenhuma tarefa aberta.", "No open tasks."));
    abertas.forEach((tf) => l.push(`- [ ] ${tf.titulo} · ${quemFaz(tf)}${tf.prazo ? ` · ${t("até", "due")} ${dia(tf.prazo)}` : ""}`));
    l.push("", `## ${t("Tarefas feitas", "Completed tasks")} (${feitas.length})`, "");
    if (!feitas.length) l.push(t("Nenhuma tarefa concluída no período.", "No tasks completed in this period."));
    feitas.forEach((tf) => l.push(`- [x] ${tf.titulo} · ${t("feita por", "done by")} ${tf.concluida_por_agente ? agenteDe(tf.concluida_por_agente, tf.concluida_por) : nome(tf.concluida_por)}${tf.concluida_em ? ` ${t("em", "on")} ${dia(tf.concluida_em)}` : ""}${tf.resultado ? ` · ${limpa(tf.resultado)}` : ""}`));
    if (d.conversa) {
      const n = d.conversa.length;
      l.push("", t(`## Conversa (${n} mensagens)`, `## Conversation (${n} ${n === 1 ? "message" : "messages"})`), "");
      d.conversa.forEach((m) => l.push(`**${autor(m)}** · ${diaHora(m.criada_em)}${m.tipo === "proposta" ? t(" · proposta", " · proposal") : m.tipo === "decisao" ? t(" · decisão", " · decision") : ""}`, "", m.texto ? gravado(m.texto) : t("(arquivo)", "(file)"), ...(m.anexos ?? []).map((a) => `📎 ${a.nome}`), ""));
    }
    return l.join("\n");
  };

  const html = (d: Dados) => {
    const md = markdown(d);
    const corpo = md.split("\n").map((linha) => {
      const tf = esc(linha).replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>");
      if (linha.startsWith("# ")) return `<h1>${tf.slice(2)}</h1>`;
      if (linha.startsWith("## ")) return `<h2>${tf.slice(3)}</h2>`;
      if (linha.startsWith("  - ")) return `<p class="sub">${tf.slice(4)}</p>`;
      if (linha.startsWith("- [ ] ")) return `<p class="item">☐ ${tf.slice(6)}</p>`;
      if (linha.startsWith("- [x] ")) return `<p class="item">☑ ${tf.slice(6)}</p>`;
      if (linha.startsWith("- ")) return `<p class="item">• ${tf.slice(2)}</p>`;
      return linha ? `<p>${tf}</p>` : "";
    }).join("\n");
    return `<!doctype html><html lang="${idioma() === "en" ? "en" : "pt-BR"}"><head><meta charset="utf-8"><title>${t("Ata", "Minutes")} · ${esc(salaNome)}</title>
<style>body{font:14px/1.55 "IBM Plex Sans",system-ui,sans-serif;color:#18181B;max-width:720px;margin:40px auto;padding:0 24px}
h1{font:600 26px/1.2 Archivo,system-ui,sans-serif;margin:0 0 8px}h2{font:600 16px/1.3 Archivo,system-ui,sans-serif;margin:28px 0 8px;padding-top:12px;border-top:1px solid #E7E6E3}
p{margin:0 0 8px}.item{padding-left:4px}.sub{padding-left:24px;color:#5F5F66}@media print{body{margin:0}}</style></head><body>${corpo}
<p style="margin-top:32px;color:#5F5F66;font-size:12px">The Sala</p></body></html>`;
  };

  const nomeArquivo = `${t("ata", "minutes")}-${salaNome.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")}-${new Date().toISOString().slice(0, 10)}`;

  const baixar = async () => {
    setIndo(true);
    const d = await juntar();
    setIndo(false);
    const a = document.createElement("a");
    a.href = URL.createObjectURL(new Blob([markdown(d)], { type: "text/markdown;charset=utf-8" }));
    a.download = `${nomeArquivo}.md`;
    a.click();
    setTimeout(() => URL.revokeObjectURL(a.href), 1000);
  };

  const imprimir = async () => {
    const janela = window.open("", "_blank"); // abre já no clique, para o navegador não bloquear
    setIndo(true);
    const d = await juntar();
    setIndo(false);
    if (!janela) return alert(t("O navegador bloqueou a nova janela. Libere janelas para esta página e tente de novo.", "Your browser blocked the new window. Allow pop-ups for this page and try again."));
    janela.document.write(html(d));
    janela.document.close();
    janela.focus();
    setTimeout(() => janela.print(), 300);
  };

  return (
    <div className="modal-fundo" onMouseDown={(e) => e.target === e.currentTarget && fechar()}>
      <div className="modal" role="dialog" aria-modal="true" aria-labelledby="ata-titulo">
        <div className="modal-topo">
          <h2 id="ata-titulo">{t("Ata da sala", "Room minutes")}</h2>
          <button className="btn-icone" onClick={fechar} aria-label={t("Fechar", "Close")}><IconeFechar /></button>
        </div>
        <p className="sub">{t("Decisões, o que aguarda decisão e as tarefas do período. Boa para mandar ao cliente ou levar para a reunião.", "Decisions, what's awaiting a decision, and the period's tasks. Great for sending to a client or bringing to a meeting.")}</p>
        <fieldset className="opcoes">
          <legend className="secao-rotulo secao-rotulo-solto">{t("Período", "Period")}</legend>
          {([[7, t("Últimos 7 dias", "Last 7 days")], [30, t("Últimos 30 dias", "Last 30 days")], [0, t("Tudo", "All time")]] as const).map(([v, r]) => (
            <label key={v} className={`opcao ${dias === v ? "marcada" : ""}`}>
              <input type="radio" name="periodo" checked={dias === v} onChange={() => setDias(v)} /><span><strong>{r}</strong></span>
            </label>
          ))}
        </fieldset>
        <label className="opcao">
          <input type="checkbox" checked={incluirConversa} onChange={(e) => setConversa(e.target.checked)} />
          <span><strong>{t("Incluir a conversa inteira", "Include the whole conversation")}</strong><span className="nota">{t("Fica bem mais longa. Sem ela, a ata tem só o que foi decidido e combinado.", "It gets much longer. Without it, the minutes only have what was decided and agreed.")}</span></span>
        </label>
        <div className="modal-acoes">
          <button className="btn" onClick={baixar} disabled={indo}>{t("Baixar .md", "Download .md")}</button>
          <button className="btn btn-cheio" onClick={imprimir} disabled={indo}>{t("Imprimir ou salvar PDF", "Print or save as PDF")}</button>
        </div>
      </div>
    </div>
  );
}
